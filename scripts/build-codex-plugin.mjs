#!/usr/bin/env node

// Builds hosts/codex/, the plugin folder Codex installs. Codex loads no hooks from a plugin whose root plugin.json is an
// Agent Plugins manifest (openai/codex rust-v0.157.0, core-plugins/src/loader.rs), and the Agent Plugins spec requires
// that manifest at the repository root for the other hosts. So Codex gets its own folder without it. Codex copies a
// plugin's regular files into its cache and skips symlinks (core-plugins/src/store.rs), so the folder holds copies.
//
//   node scripts/build-codex-plugin.mjs           write hosts/codex/
//   node scripts/build-codex-plugin.mjs --check   exit 1 when hosts/codex/ differs from its sources

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
export const CODEX_PLUGIN_DIR = "hosts/codex";
const README = `# Freeflow for Codex

Generated by \`npm run build:codex\` from the repository root; do not edit. Codex installs this folder because it loads
no hooks from a plugin whose root \`plugin.json\` is an Agent Plugins manifest. See
[Prompt assembly](../../dev-docs/subsystems/prompt-assembly.md#host-delivery).
`;

/** Files under `dir` that Git tracks or would track, so ignored and scratch files never ship. */
function sourceFiles(dir) {
  const output = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "--", dir], {
    cwd: root,
    encoding: "utf8",
  });
  return output.split("\n").filter((file) => file && existsSync(join(root, file)));
}

/** A built module and every relative module it imports. */
function moduleClosure(entry, seen = new Set()) {
  if (seen.has(entry)) return seen;
  seen.add(entry);
  for (const [, specifier] of readFileSync(join(root, entry), "utf8").matchAll(/^import[^;]*?from\s+"([^"]+)"/gm)) {
    if (specifier.startsWith(".")) moduleClosure(relative(root, resolve(root, dirname(entry), specifier)), seen);
  }
  return seen;
}

/** Every file of the Codex plugin, as plugin-relative path -> content. */
export function codexPluginFiles() {
  const files = new Map();
  const copy = (path) => files.set(path, readFileSync(join(root, path)));
  for (const file of sourceFiles("skills")) copy(file);
  for (const file of [
    ".codex-plugin/plugin.json",
    "runtime/prompts/core.md",
    "runtime/prompts/interaction-contract.md",
    "runtime/prompts/working-method.md",
    "hooks/codex/hooks.json",
    "hooks/adapters/codex-session-start.mjs",
    "hooks/shared/runtime-context.mjs",
    "assets/freeflow-plugin-icon-transparent.png",
    "LICENSE",
    "NOTICE",
    ...sourceFiles("licenses"),
    ...moduleClosure("pi-extension/dist/host/config-validation.js"),
  ])
    copy(file);
  files.set("README.md", Buffer.from(README));
  return files;
}

function existingFiles(dir, base = dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? existingFiles(path, base) : [relative(base, path)];
  });
}

/** Paths that differ between hosts/codex/ and what the build would write. */
export function codexPluginDifferences() {
  const target = join(root, CODEX_PLUGIN_DIR);
  const expected = codexPluginFiles();
  const differences = [];
  for (const [path, content] of expected) {
    const file = join(target, path);
    if (!existsSync(file) || !readFileSync(file).equals(content)) differences.push(path);
  }
  for (const path of existingFiles(target)) if (!expected.has(path)) differences.push(`${path} (not a source)`);
  return differences;
}

function build() {
  const target = join(root, CODEX_PLUGIN_DIR);
  rmSync(target, { recursive: true, force: true });
  for (const [path, content] of codexPluginFiles()) {
    mkdirSync(dirname(join(target, path)), { recursive: true });
    writeFileSync(join(target, path), content);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  if (process.argv.includes("--check")) {
    const differences = codexPluginDifferences();
    if (differences.length) {
      console.error(`${CODEX_PLUGIN_DIR}/ is out of date; run npm run build:codex. Differs: ${differences.join(", ")}`);
      process.exit(1);
    }
    console.log(`${CODEX_PLUGIN_DIR}/ matches its sources.`);
  } else {
    build();
    console.log(`Built ${CODEX_PLUGIN_DIR}/.`);
  }
}
